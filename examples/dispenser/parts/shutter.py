"""Шибер: пластина с окном и кулачковым хвостовиком.

Порт `nozzle.py::_shutter_slide`. Деталь — ФУНКЦИЯ ОТ ХОДА люльки: на ходе 0
окно шибера уведено от выхода и канал закрыт, к ходу SHUTTER_OPEN_STROKE окно
встаёт под выход. Ровно это и развёртывают проверки хода.

Смещение линейное по ходу: палец каретки ведёт шибер по кулачковому пазу с
постоянным наклоном (подъём SLIDE_TRAVEL на ходе SHUTTER_OPEN_STROKE).

Печатается НА РЕБРЕ, гранью хвостовика на стол (`print_up="+Y"`), как в
оригинале (`export_plates.py`: `RX(90)`), из PETG. Что это не случайность, видно по
самой геометрии оригинала: окно шибера — капля носиком в +Y, то есть сделано
под печать ровно в этой позе.

У оригинала опорная грань — пластина кулачка с пазом, 483 мм² прилипания. В
порте кулачка нет (ход задан линейно), и той же грани остаётся 96 мм².
Перевёрнутым шибер лёг бы на стол всей пластиной, но так его не печатали, и
выбирать ориентацию по площади вопреки записанной — не дело порта.
"""

from datum.build import P, part
from datum.geom import box, diff, move, prism_xy, teardrop_poly


@part("шибер", color="#c9723b", print_up="+Y")
def build(u: float = 0.0):
    """u — ход люльки в миллиметрах, от 0 (закрыто) до STROKE_MAX."""
    # Шибер открывается только на первом участке хода; дальше он уже упёрся.
    advance = P.SLIDE_TRAVEL * min(max(u, 0.0) / P.SHUTTER_OPEN_STROKE, 1.0)

    z0 = P.NOZ_Z0 + P.FLOOR_T + 0.1
    plate = box(P.SLIDE_X0, P.SLIDE_X0 + P.SLIDE_L,
                P.TUBE_Y - P.SLIDE_W / 2, P.TUBE_Y + P.SLIDE_W / 2,
                z0, z0 + P.SLIDE_T)

    # Окно в покое смещено от выхода: канал перекрыт телом шибера. Окно —
    # КАПЛЯ носиком в +Y, как у оригинала: на ребре +Y смотрит вверх, и свод
    # окна печатается скатами по 45°, а не висит над пустотой.
    drop = teardrop_poly(P.PORT_D, cx=P.PORT_REST_X, cy=P.TUBE_Y, nose="+y")
    window = prism_xy(list(drop.exterior.coords)[:-1], z0 - 1, z0 + P.SLIDE_T + 1)

    # Шейка хвостовика: проходит сквозь пол к пальцу каретки.
    neck = box(13.0, 19.0,
               P.TUBE_Y - P.SLIDE_W / 2, P.TUBE_Y - P.SLIDE_W / 2 + 3.0,
               P.NOZ_Z0 - 0.3, z0 + 0.5)

    return move(diff(plate, [window]) + neck, dx=advance)
