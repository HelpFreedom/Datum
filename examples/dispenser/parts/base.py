"""Основание: плита, на которой стоит вся башня.

Нужно здесь ради проверок устойчивости: центр масс над опорой и опрокидывание
при нажатии. Форма опоры важнее габарита — у плиты с вырезами настоящая опора
меньше, чем кажется.
"""

from datum.build import P, part
from datum.geom import box, diff


@part("основание", color="#6b7280", print_up="+Z")
def build():
    plate = box(-P.BASE_W / 2, P.BASE_W / 2, -P.BASE_D / 2, P.BASE_D / 2, 0.0, P.BASE_T)

    # Облегчение: карманы снизу, как в настоящем основании. Опору они не
    # уменьшают — края остаются, — но массу снимают заметно.
    #
    # КАЖДЫЙ КАРМАН РАЗДЕЛЁН РЕБРОМ, и это не украшение. Сплошной карман
    # 56×56 давал мост в 55.5 мм — вдвое больше того, что пластик проходит без
    # провисания. Нашла это `bridge_span`; в оригинале карманы были взяты как
    # есть, печатностью никто не занимался. Ребро делит пролёт пополам: 26 мм
    # проходятся спокойно, а масса растёт всего на три грамма.
    rib = P.POCKET_RIB / 2
    half = P.POCKET_W / 2
    pockets = []
    for sx in (-1, 1):
        for sy in (-1, 1):
            cx, cy = sx * 40.0, sy * 42.0
            # Две половинки кармана, между ними ребро шириной POCKET_RIB.
            for x0, x1 in ((cx - half, cx - rib), (cx + rib, cx + half)):
                pockets.append(box(x0, x1, cy - half, cy + half,
                                   -1.0, P.BASE_T - 2.5))
    return diff(plate, pockets)
