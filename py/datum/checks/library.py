# Имена параметров бывают не только латинские: в проектах на русском они
# кириллические. `[A-Za-z_]` молча пропускал такую ссылку внутрь проверки строкой,
# и падало уже там, невнятным TypeError. Поэтому \w с юникодом.
_PARAM_REF = re.compile(r"^\$\{params\.([^\W\d]\w*)\}$", re.UNICODE)
_EXPR_REF = re.compile(r"^\$\{expr:\s*(.+)\}$", re.S)
_ANY_REF = re.compile(r"\$\{")


@dataclass(frozen=True, slots=True)
class PartRef:
    name: str


@dataclass(frozen=True, slots=True)
class PartFnRef:
    name: str


def resolve_args(args: dict, entry: LibraryEntry, params) -> dict:
    """Развернуть ссылки в аргументах. Детали остаются ссылками — их разрешит проект."""
    from datum.doc.expr import evaluate

    def one(key: str, value: Any) -> Any:
        if isinstance(value, str):
            if value.startswith("@"):
                name = value[1:]
                return PartFnRef(name) if key in entry.fn_args else PartRef(name)
            m = _PARAM_REF.match(value)
            if m:
                name = m.group(1)
                if name not in params:
                    raise KeyError(f"в аргументе {key!r} ссылка на неизвестный параметр {name!r}")
                return params[name]
            m = _EXPR_REF.match(value)
            if m:
                expr = m.group(1).strip()
                from datum.doc.expr import referenced_names
                # Читаем имена ЧЕРЕЗ params: если это прокси, обращения запишутся
                # и попадут в depends_on проверки.
                env = {n: params[n] for n in referenced_names(expr)}
                return evaluate(expr, env)
        if isinstance(value, list):
            return [one(key, v) for v in value]
        if isinstance(value, dict):
            return {k: one(k, v) for k, v in value.items()}
        return value

    out = {k: one(k, v) for k, v in (args or {}).items()}

    # Аргументы, ожидающие деталь, обязаны быть ссылками — иначе опечатка молча
    # превратится в строку и уедет внутрь проверки.
    for key in entry.solid_args + entry.fn_args:
        if key in out and isinstance(out[key], str):
            raise ValueError(
                f"аргумент {key!r} проверки {entry.name!r} должен ссылаться на деталь "
                f"через «@имя», получено {out[key]!r}")

    # Ни одна ссылка не должна уцелеть неразобранной: иначе она уедет внутрь
    # проверки строкой и упадёт там с невнятной ошибкой.
    def scan(key: str, value) -> None:
        if isinstance(value, str) and _ANY_REF.search(value):
            raise ValueError(
                f"в аргументе {key!r} проверки {entry.name!r} осталась неразобранная "
                f"ссылка {value!r}. Допустимы «@деталь», «${{params.ИМЯ}}» и "
                f"«${{expr: формула}}»")
        if isinstance(value, list):
            for v in value:
                scan(key, v)
        elif isinstance(value, dict):
            for k, v in value.items():
                scan(k, v)

    for key, value in out.items():
        scan(key, value)
    return out
