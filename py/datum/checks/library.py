"""Каталог проверок для декларативного описания в `checks/checks.yaml`.

Строка описания выглядит так:

    - id: shutter.escape
      use: escape
      args:
        part: "@shutter"          # «@имя» — собранная деталь проекта
        holder: "@case"
        dirs: ["+Z", "-Z", "+Y"]
        gap: ${params.CL_SLIDE}   # значение параметра
        hold_vol: ${expr: HOLD_MIN * 1.0}

Три вида ссылок разбираются явно, чтобы не гадать по типу значения:
  «@имя»          — деталь (или функция от хода, если проверка этого ждёт);
  ${params.ИМЯ}   — значение параметра;
  ${expr: ...}    — выражение по параметрам, через тот же безопасный вычислитель.

ВАЖНО: ссылки со знаком $ нужно брать в кавычки. YAML иначе видит в «${» начало
вложенного отображения и отказывается разбирать строку — ошибка невнятная
(«expected ',' or '}'»), а причина неочевидна.
"""

