@dataclass(frozen=True, slots=True)
class LibraryEntry:
    name: str
    fn: Callable[..., Any]
    solid_args: tuple[str, ...] = ()       # аргументы, ожидающие собранную деталь
    fn_args: tuple[str, ...] = ()          # аргументы, ожидающие функцию от хода
    many: bool = False                     # возвращает список результатов
    group: str = ""
    doc: str = ""
    #: ЧТО ПРОВЕРКА ПРИНИМАЕТ НА ВЕРУ — и, значит, где она неприменима.
    #:
    #: Поле обязательное, и это не формальность. Механизмов не перечислить, и
    #: попытка РАСПОЗНАТЬ, что перед нами, проваливается: дважды построенный
    #: различитель «защёлка против затора» дважды не пережил замера (см.
    #: `checks/assembly.py::_hint`). Поэтому применимость не определяется, а
    #: ОБЪЯВЛЯЕТСЯ — здесь, один раз, рядом с самой проверкой. Тест не даёт
    #: завести проверку с пустым полем: пусть автор новой скажет, где она врёт,
    #: пока помнит.
    assumes: str = ""


def _entry(name, fn, *, solid=(), fns=(), many=False, group="", assumes="") -> LibraryEntry:
    return LibraryEntry(name=name, fn=fn, solid_args=tuple(solid), fn_args=tuple(fns),
                        many=many, group=group, assumes=assumes.strip(),
                        doc=(fn.__doc__ or "").strip().split("\n")[0])


