"""Что решаем: материал, тело, нагрузка.

ЕДИНИЦЫ. Миллиметры, мегапаскали, ньютоны. МПа = Н/мм², поэтому перемещения
выходят сразу в миллиметрах, и переводить ничего не нужно. Любая величина,
пришедшая в других единицах, — ошибка, которую решатель не заметит: он сложит
числа и вернёт бессмыслицу с уверенным видом.

СВОЙСТВ МАТЕРИАЛА ВНУТРИ НЕТ. Ни модуля, ни коэффициента Пуассона, ни
плотности: они зависят от материала, принтера и ориентации слоёв, а
спрятанные в коде становятся невидимым допущением. Приходят аргументами,
объявляются параметрами с происхождением. То же правило, что в
`checks/analysis.py`, и оно там заперто тестом, читающим исходник.

БРУС — ЗДЕСЬ, ПРОИЗВОЛЬНОЕ ТЕЛО — В `solve_faces`. Брус постоянного
прямоугольного сечения строится точно и без мешера вовсе, а именно он описывает
то, ради чего МКЭ здесь заводился: флексуры, защёлкивающиеся консоли, живые
петли. На нём считают проверки каталога (`flexure_force_fem`,
`insertion_force`): у структурированной сетки есть лестница сеток и вилка.
Произвольную деталь операция `fem_solve` берёт сеткой fTetWild (`tetmesh.py`)
и только с тестом заплаты на ТОЙ ЖЕ сетке — посчитать молча по плохой сетке
было бы хуже отказа.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

__all__ = ["Material", "Bar", "FemError"]


class FemError(RuntimeError):
    """Задача поставлена так, что решать её нельзя."""


#: Модуль упругости, МПа: всё, что бывает у материалов, с запасом в обе стороны.
MODULUS_RANGE_MPA = (1e-3, 1e7)


@dataclass(frozen=True, slots=True)
class Material:
    """Линейно-упругий изотропный материал.

    `modulus` — модуль Юнга в МПа, `poisson` — коэффициент Пуассона.
    Для печатного PLA вдоль слоёв около 2000…3500 МПа и 0.33…0.36, но это НЕ
    умолчания: числа зависят от партии, температуры и ориентации, и подставить
    их здесь значило бы решить за человека.
    """

    modulus: float
    poisson: float
    name: str = ""

    def __post_init__(self) -> None:
        if not math.isfinite(self.modulus) or self.modulus <= 0:
            raise FemError(f"модуль должен быть положительным, получено {self.modulus!r}")
        # Вне этих пределов нет материалов, а есть опечатка в единицах: 1e308
        # МПа ронял решатель сырым LinAlgError, 1e-300 давал прогиб nan.
        lo, hi = MODULUS_RANGE_MPA
        if not lo <= self.modulus <= hi:
            raise FemError(f"модуль {self.modulus:g} МПа — вне {lo:g}…{hi:g} МПа (от гелей "
                           f"до алмаза, 1.2·10⁶): проверьте единицы — модуль в МПа, "
                           f"у PLA около 2000…3500")
        # Верхняя граница не 0.5, а чуть меньше: при 0.5 материал несжимаем, и
        # параметр Ламе λ обращается в бесконечность. Отрицательные значения
        # физически существуют (ауксетики), но печатный пластик к ним не
        # относится, и чаще это опечатка.
        if not (0.0 <= self.poisson < 0.5):
            raise FemError(
                f"коэффициент Пуассона должен лежать в [0, 0.5), получено "
                f"{self.poisson!r}. При 0.5 материал несжимаем и λ обращается "
                f"в бесконечность — такой случай нужна другая формулировка")

    @property
    def lame(self) -> tuple[float, float]:
        """Параметры Ламе (λ, μ). μ — он же модуль сдвига G."""
        e, nu = self.modulus, self.poisson
        return (e * nu / ((1 + nu) * (1 - 2 * nu)), e / (2 * (1 + nu)))

    @property
    def shear_modulus(self) -> float:
        return self.lame[1]


@dataclass(frozen=True, slots=True)
class Bar:
    """Призматический брус: длина вдоль X, сечение width×thickness.

    СЕЧЕНИЕ ЦЕНТРИРОВАНО по Y и Z, то есть брус занимает
    x ∈ [0, length], y ∈ [−width/2, width/2], z ∈ [−thickness/2, thickness/2].
    Это не украшение: плоскости y=0 и z=0 становятся плоскостями симметрии, и
    условия закрепления на них согласуются с точным решением эталонных задач.
    Сдвинь сечение — и самопроверка начнёт врать.
    """

    length: float
    width: float
    thickness: float

    def __post_init__(self) -> None:
        for name, value in (("length", self.length), ("width", self.width),
                            ("thickness", self.thickness)):
            if not math.isfinite(value) or value <= 0:
                raise FemError(f"{name} должен быть положительным, получено {value!r}")

    @property
    def inertia(self) -> float:
        """Момент инерции сечения относительно оси Y (изгиб в плоскости XZ)."""
        return self.width * self.thickness ** 3 / 12

    @property
    def area(self) -> float:
        return self.width * self.thickness

    @property
    def slenderness(self) -> float:
        """Отношение длины к толщине. Балочные формулы верны при большом."""
        return self.length / self.thickness
