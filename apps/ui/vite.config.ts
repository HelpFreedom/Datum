import react from "@vitejs/plugin-react";
import { defineConfig } from "vite";

// Цель сборки — именно тот Chromium, что внутри Electron 44 (152). Ставить
// цель ниже значит просить лишние преобразования, выше — получить синтаксис,
// которого нет.
//
// ИМЕНА ФАЙЛОВ В БАНДЛЕ ОБЯЗАНЫ БЫТЬ ЛАТИНСКИМИ. Сервер отдаёт /assets/<имя>
// без токена только по узкому выражению [A-Za-z0-9_-]+(\.[A-Za-z0-9_-]+)+ —
// это и есть защита от обхода каталога. Файл с кириллицей в имени под него не
// подойдёт и получит 403. Код внутри файлов — по-русски, имена — латиницей.
export default defineConfig({
  root: __dirname,
  base: "/",
  plugins: [react()],
  build: {
    outDir: "dist",
    emptyOutDir: true,
    target: "chrome152",
    // Карты исходников — только по просьбе: это 5 МБ, и сервер раздаёт их через
    // /assets наравне с кодом. Для отладки: DATUM_SOURCEMAP=1 npm run build.
    sourcemap: process.env.DATUM_SOURCEMAP === "1",
    // Один кусок на 1.3 МБ (three, xterm, react) — сознательно: окно грузится с
    // петли, и дробить его на части ради сети, которой нет, незачем.
    chunkSizeWarningLimit: 2000,
    // Ничего не встраивать в `data:`. Мелкий набор знаков шрифта Vite иначе
    // вшивает в CSS строкой, а CSP пускает шрифты только со своего
    // происхождения (`font-src 'self'`) — и правильно делает. Ослаблять CSP
    // ради удобства сборки незачем: файл с петли стоит ноль.
    assetsInlineLimit: 0,
  },
});
