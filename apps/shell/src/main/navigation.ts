/**
 * Куда окну позволено уходить.
 *
 * Вынесено отдельным модулем БЕЗ импорта electron, чтобы решение можно было
 * проверить тестом. Живая проба (`scripts/ui/security.cjs`) показывает, что
 * окно действительно никуда не уходит; здесь проверяется таблица решений
 * целиком, включая ветку «наружу», которую живьём не потрогать: она открывает
 * настоящий браузер.
 */

export type NavigationVerdict =
  | "свой"      // своё происхождение — пускаем
  | "наружу"    // http(s) на сторону — отдаём системному браузеру
  | "запрет";   // всё прочее — молча не пускаем

/**
 * СРАВНИВАЮТСЯ ПРОИСХОЖДЕНИЯ, А НЕ СТРОКИ. Первая версия писала
 * `url.startsWith(origin)`, и это ловушка: порт сервера случайный, поэтому
 * своё «http://127.0.0.1:3332» оказывается ПРЕФИКСОМ чужого
 * «http://127.0.0.1:33321/…», и чужая страница на соседнем порту считалась бы
 * своей. Разбор URL такой ошибки не допускает.
 */
export function navigationVerdict(url: string, origin: string): NavigationVerdict {
  let target: URL;
  try {
    target = new URL(url);
  } catch {
    return "запрет";               // не URL вовсе — тем более не пускаем
  }
  if (target.origin === new URL(origin).origin) return "свой";
  return target.protocol === "http:" || target.protocol === "https:"
    ? "наружу"
    : "запрет";
}
